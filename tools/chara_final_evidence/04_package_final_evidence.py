    create_meta_files()
    core_zip_path = os.path.join(REPORTS_DIR, "CHARA_FINAL_EVIDENCE_CORE.zip")

    # CSV files from reports dir
    csv_files = [
        "RUN_PROVENANCE.csv",
        "FORCEFIELD_COMPARISON.csv",
        "TRAJECTORY_TIME_CHECKS.csv",
        "CONSTRUCT_IDENTITY.csv",
        "RESIDUE_MAPPING.csv",
        "DIAGNOSTICS_CORRECTED.csv",
        "CLAIM_CORRECTIONS.csv",
        "CLOSEST_WORK_VERIFIED.csv",
        "CONFIRMATION_DATA_OPTIONS.csv",
        "EXPERIMENT_SPECIFICATION.md"
    ]

    manifest_lines = []

    with zipfile.ZipFile(core_zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        # Meta files
        for f in ["START_HERE.txt", "FINAL_FACTS.md", "protocol_and_environment.json", "verify_final_evidence.py"]:
            src = os.path.join(STAGING_DIR, f)
            arcname = f
            zf.write(src, arcname)
            manifest_lines.append(f"{sha256_file(src)}  {arcname}")

        # CSV and markdown files
        for f in csv_files:
            src = os.path.join(REPORTS_DIR, f)
            if os.path.exists(src):
                arcname = f"tables/{f}" if f.endswith(".csv") else f
                zf.write(src, arcname)
                manifest_lines.append(f"{sha256_file(src)}  {arcname}")

        # Code snapshot
        tools_dir = os.path.join(BASE_DIR, "tools", "chara_final_evidence")
        for root, dirs, files in os.walk(tools_dir):
            for f in files:
                src = os.path.join(root, f)
                rel = os.path.relpath(src, tools_dir).replace("\\", "/")
                arcname = f"code/{rel}"
                zf.write(src, arcname)
                manifest_lines.append(f"{sha256_file(src)}  {arcname}")

        # Source scripts snapshot
        src_scripts = [
            "scripts/02_phase2_cg.py",
            "scripts/03_phase3_gromacs.py",
            "scripts/setup_ptpn11_replicates.py",
            "scripts/19_fix_ptpn11_rep1_frames.py"
        ]
        for s in src_scripts:
            src = os.path.join(BASE_DIR, s)
            if os.path.exists(src):
                arcname = f"source_snapshots/{os.path.basename(s)}"
                zf.write(src, arcname)
                manifest_lines.append(f"{sha256_file(src)}  {arcname}")

        # Write manifest file
        manifest_text = "\n".join(manifest_lines) + "\n"
        zf.writestr("manifest_checksums.sha256", manifest_text)

    size = os.path.getsize(core_zip_path)
    print(f"[✓] Created CHARA_FINAL_EVIDENCE_CORE.zip ({size:,} bytes, {size / (1024*1024):.2f} MiB)")
    return core_zip_path

